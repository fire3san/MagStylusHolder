#!/usr/bin/env python3
"""Build the static product gallery and its shared bilingual image data."""
from pathlib import Path
from html import escape
import json,re
ROOT=Path(__file__).resolve().parents[1]
scenes=json.loads((ROOT/'assets/story/lifestyle-scenes.json').read_text())
def t(text,tag='span',cls=''):
 c=f' class="{cls}"' if cls else ''
 return f'<{tag}{c} data-zh="{escape(text["zh"],quote=True)}" data-en="{escape(text["en"],quote=True)}">{escape(text["zh"])}</{tag}>'

cards=[]
for i,s in enumerate(scenes):
 name=escape(s['name']);device=escape(s['device']);label=f'{i+1:02d} / {name}'
 cards.append(f'''          <article class="realworld-card" data-scene="{s['key']}">
            <div class="realworld-art" role="button" tabindex="0" aria-label="{name} · {device} — 圖片放大 / Image preview" data-gallery="realworld" data-index="{i}">
              <img src="{s['src']}" alt="{name} holder with {device}; AI concept scene based on CAD references" width="1536" height="1024" loading="lazy">
              <span class="realworld-tag">{label} · {device}</span>
              <span class="realworld-zoom-hint" aria-hidden="true">＋</span>
            </div>
            <div class="realworld-body">
              <span class="realworld-scenario">{name} / {device}</span>
              {t(s['title'],'h3')}
              {t(s['desc'],'p')}
              <button class="gallery-cad-link" data-inspect="{s['model']}" aria-label="在 3D 中檢視 / Inspect {name}">
                <img src="{s['cad']}" alt="{name} actual CAD reference" width="70" height="70" loading="lazy">
                <span><strong>{name}</strong><span data-zh="對照實際 CAD 模型 ↗" data-en="Compare the actual CAD model ↗">對照實際 CAD 模型 ↗</span></span>
              </button>
            </div>
          </article>''')
header='''      <!-- Section: real-world -->
      <section class="section realworld-section" id="real-world">
        <div class="section-label">IN EVERYDAY LIFE / 從設計走進日常</div>
        <div class="section-heading">
          <h2 data-zh="隨身、閱讀與即興創作。" data-en="Carry, read, and make room for ideas.">隨身、閱讀與即興創作。</h2>
          <p data-zh="從 BOOX Go 6 (Gen II) 到 iPhone 與 iPhone Duo。讓每一種收筆方式，都看得見自己的形狀與位置。" data-en="From BOOX Go 6 (Gen II) to iPhone and iPhone Duo. See the shape and placement behind each way to carry a pen.">從 BOOX Go 6 (Gen II) 到 iPhone 與 iPhone Duo。讓每一種收筆方式，都看得見自己的形狀與位置。</p>
        </div>
        <p class="gallery-disclosure" data-zh="AI 情境示意，以產品 CAD 與官方設備外觀為參考；不是實物測試照片。每張圖均附對應 CAD 模型，實際配合仍需打樣確認。" data-en="AI concept scenes informed by product CAD and official device appearances, not physical test photos. Each scene links to its CAD reference; physical fit still needs prototype validation.">AI 情境示意，以產品 CAD 與官方設備外觀為參考；不是實物測試照片。每張圖均附對應 CAD 模型，實際配合仍需打樣確認。</p>
        <div class="realworld-grid">
'''
footer='''
        </div>
        <p class="gallery-sources"><span data-zh="設備外觀參考：" data-en="Device appearance references:">設備外觀參考：</span> <a href="https://shop.boox.com/products/go6gen2" target="_blank" rel="noopener">BOOX Go 6 (Gen II)</a> · <a href="https://www.apple.com/uk/iphone-17/" target="_blank" rel="noopener">iPhone 17</a> · <a href="https://www.apple.com/iphone-duo/" target="_blank" rel="noopener">iPhone Duo</a></p>
      </section>
'''
p=ROOT/'index.html';html=p.read_text();start=html.index('      <!-- Section: real-world -->');end=html.index('      <!-- Section: origin -->',start)
html=html[:start]+header+'\n'.join(cards)+footer+html[end:]
if 'js/lifestyle.js' not in html:html=html.replace('<script src="js/main.js', '<script src="js/lifestyle.js?v=gallery-v7"></script>\n    <script src="js/main.js')
html=re.sub(r'js/main.js\?v=[^"]+', 'js/main.js?v=gallery-v7',html)
p.write_text(html)
(ROOT/'js/lifestyle.js').write_text('// Generated by scripts/build-lifestyle.py from assets/story/lifestyle-scenes.json.\nwindow.LIFESTYLE_SCENES = '+json.dumps(scenes,ensure_ascii=False,indent=2)+';\n')
print(f'Built {len(scenes)} source-matched gallery cards.')
